def _compose_service_running(root, service=OC2API_SERVICE):
    """判断 docker compose 服务是否在运行（失败一律返回 False）。"""
    if shutil.which("docker") is None:
        return False
    try:
        result = subprocess.run(
            ["docker", "compose", "ps", "--format", "json"],
            cwd=str(root),
            capture_output=True,
            text=True,
            timeout=30,
        )
    except Exception:
        return False
    if result.returncode != 0:
        return False
    text = (result.stdout or "").strip()
    entries = []
    if text:
        try:
            parsed = json.loads(text)
            entries = parsed if isinstance(parsed, list) else [parsed]
        except ValueError:
            for line in text.splitlines():
                line = line.strip()
                if not line:
                    continue
                try:
                    entries.append(json.loads(line))
                except ValueError:
                    continue
    for entry in entries:
        if not isinstance(entry, dict):
            continue
        label = " ".join(str(entry.get(key) or "") for key in ("Service", "Name", "Names", "ID"))
        if service not in label:
            continue
        state = str(entry.get("State") or entry.get("Status") or "").lower()
        if not state or "run" in state or "up" in state:
            return True
    try:
        fallback = subprocess.run(
            ["docker", "compose", "ps", "-q", service],
            cwd=str(root),
            capture_output=True,
            text=True,
            timeout=30,
        )
        return fallback.returncode == 0 and bool((fallback.stdout or "").strip())
    except Exception:
        return False


def _webui_reload(env):
    base = str(env.get("OC2API_WEBUI_URL") or OC2API_WEBUI_URL).rstrip("/")
    username = env.get("OC2API_WEBUI_USER") or "admin"
    password = env.get("OC2API_WEBUI_PASSWORD") or ""
    status, raw, response_headers = _http_request(
        "POST",
        base + "/api/auth/login",
        payload={"username": username, "password": password},
        timeout=15,
    )
    text = raw.decode("utf-8", "replace") if raw else ""
    if status == 0:
        raise RuntimeError("无法连接 WebUI %s: %s" % (base, _short(text, 200)))
    if status >= 400:
        raise RuntimeError("WebUI 登录失败 HTTP %s: %s" % (status, _short(text, 200)))
    cookie = _cookies_from_headers(response_headers)
    body = None
    try:
        body = json.loads(text) if text else {}
    except ValueError:
        body = {}
    csrf = _find_nested_key(body if isinstance(body, dict) else {}, ["csrf", "csrf_token", "csrfToken"])
    headers = {}
    if cookie:
        headers["Cookie"] = cookie
    if csrf:
        headers["X-CSRF-Token"] = str(csrf)
    status, raw, _headers = _http_request(
        "POST", base + "/api/config/reload", headers=headers, payload={}, timeout=30
    )
    text = raw.decode("utf-8", "replace") if raw else ""
    if status == 0:
        raise RuntimeError("config/reload 请求失败: %s" % _short(text, 200))
    if status >= 400:
        raise RuntimeError("config/reload HTTP %s: %s" % (status, _short(text, 200)))
    _ok("WebUI 配置热重载成功 (%s/api/config/reload)" % base)


def _sync_opencode2api_container(root, config_path, env):
    root = Path(root)
    if shutil.which("docker") is None:
        _info("未检测到 docker 命令，跳过容器同步。")
        _info("部署机上请手工执行: docker compose restart opencode2api")
        return
    if not (root / "docker-compose.yml").exists():
        _info("未找到 %s，跳过容器同步。" % (root / "docker-compose.yml"))
        return
    try:
        running = _compose_service_running(root)
    except Exception as exc:
        _warn("检测容器状态失败: %s" % exc)
        running = False
    if not running:
        _info("容器 %s 未运行，跳过 docker compose cp 与热重载。" % OC2API_SERVICE)
        _info("配置已写入 %s；启动容器后请执行: docker compose restart opencode2api" % config_path)
        return
    try:
        result = subprocess.run(
            [
                "docker",
                "compose",
                "cp",
                "%s/config.json" % OC2API_SERVICE,
                "%s:%s" % (OC2API_SERVICE, OC2API_CONTAINER_CONFIG_PATH),
            ],
            cwd=str(root),
            capture_output=True,
            text=True,
            timeout=120,
        )
        if result.returncode != 0:
            raise RuntimeError(_short((result.stderr or result.stdout or "").strip(), 300))
        _ok("已同步配置进容器: %s:%s" % (OC2API_SERVICE, OC2API_CONTAINER_CONFIG_PATH))
    except Exception as exc:
        _warn("docker compose cp 失败: %s" % exc)
        _info("请手工执行: docker compose restart opencode2api")
        return
    try:
        _webui_reload(env)
    except Exception as exc:
        _warn("WebUI 热重载失败: %s" % exc)
        _info("请手工执行: docker compose restart opencode2api")


def render(root):
    """从 accounts.yaml + .env 渲染三处产物。返回 0 表示成功。"""
    root = Path(root)
    _banner("poolctl render")
    config = load_accounts(root)
    env = load_env(root)
    _require_env(env, REQUIRED_ENV_KEYS, root)

    for key, reason in _secret_problems(env):
        _warn("%s %s；请执行 poolctl rotate-secret 轮换" % (key, reason))

    devin_pool = _section(config, "devin_pool")
    mode = str(devin_pool.get("mode") or "pro-only").strip().lower()
    if mode not in ("pro-only", "max-hybrid"):
        raise PoolctlError(
            "devin_pool.mode 必须是 pro-only 或 max-hybrid，当前值: %r" % devin_pool.get("mode")
        )
    accounts = _devin_accounts(devin_pool)

    opencode_pool = _section(config, "opencode_go_pool")
    go_keys = [str(key).strip() for key in _as_list(opencode_pool.get("keys"), "opencode_go_pool.keys")]
    go_keys = [key for key in go_keys if key]
    proxies = [
        str(proxy).strip() for proxy in _as_list(opencode_pool.get("proxies"), "opencode_go_pool.proxies")
    ]
    proxies = [proxy for proxy in proxies if proxy] or ["direct"]

    goat_pool = config.get("command_code_goat_pool") or {}
    if not isinstance(goat_pool, dict):
        raise PoolctlError("accounts.yaml 的 command_code_goat_pool 必须是映射(dict)")
    goat_keys = []
    for index, item in enumerate(_as_list(goat_pool.get("keys"), "command_code_goat_pool.keys"), 1):
        if isinstance(item, str):
            api_key, weight, name = item.strip(), 1, "goat-%d" % index
        elif isinstance(item, dict):
            api_key = str(item.get("api_key") or "").strip()
            name = str(item.get("name") or "goat-%d" % index)
            weight_raw = item.get("weight", 1)
            try:
                weight = int(weight_raw if weight_raw is not None else 1)
            except (TypeError, ValueError):
                raise PoolctlError(
                    "command_code_goat_pool.keys 第 %d 项 weight 必须是整数，当前值: %r"
                    % (index, weight_raw)
                )
        else:
            raise PoolctlError("command_code_goat_pool.keys 第 %d 项必须是字符串或映射" % index)
        if not api_key:
            raise PoolctlError("command_code_goat_pool.keys 第 %d 项缺少 api_key" % index)
        goat_keys.append({"name": name, "api_key": api_key, "weight": weight})

    # --- 1. Devin 凭据 JSON ------------------------------------------------
    auths_dir = root / "cliproxy" / "auths"
    auths_dir.mkdir(parents=True, exist_ok=True)
    expected_names = set()
    max_count = 0
    pro_count = 0
    for account in accounts:
        plan_lower = account["plan"].lower()
        if plan_lower == "max":
            max_count += 1
        elif plan_lower == "pro":
            pro_count += 1
        if mode == "max-hybrid" and plan_lower == "max":
            weight = account["weight"] if account["weight"] is not None else 7
        else:
            weight = account["weight"] if account["weight"] is not None else 1
        credential = {
            "type": "devin",
            "api_key": account["session_token"],
            "email": account["email"],
            "plan": account["plan"],
            "weight": weight,
        }
        if mode == "max-hybrid" and plan_lower == "pro":
            # 凭据级 excluded_models 会整表覆盖 oauth.excluded-models（不合并），
            # 所以 Pro 号要把家族前缀排除也一并带上——否则 max-hybrid 下 Pro
            # 反而会暴露全部 Devin 模型。
            credential["excluded_models"] = list(PRO_EXCLUDED_MODELS) + list(DEVIN_EXCLUDED_MODELS)
        filename = "%s.json" % account["id"]
        expected_names.add(filename)
        atomic_write_json(auths_dir / filename, credential)
        _ok("凭据 %s (plan=%s, weight=%d%s)"
            % (
                (auths_dir / filename).relative_to(root),
                account["plan"],
                weight,
                ", 已排除付费模型" if "excluded_models" in credential else "",
            ))

    # opencode-go-quota 插件 AuthProvider 凭据：池综合卡一张，
    # quota.fetch 聚合所有 key（顶部综合三行 + 逐 key 分组）。
    expected_g = set()
    if go_keys:
        pname = "opencode-go-pool.json"
        atomic_write_json(
            auths_dir / pname,
            {"type": "opencode-go", "api_key": "__pool__", "name": "OpenCode Go Pool"},
        )
        expected_g.add(pname)
        _ok(f"凭据 {pname} (opencode-go 综合配额)")
    for stale in sorted(auths_dir.glob("opencode-go-*.json")):
        if stale.name not in expected_g:
            stale.unlink()
            _warn(f"已删除过期凭据: {stale.relative_to(root)}")

    for stale in sorted(auths_dir.glob("devin-*.json")):
        if stale.name in expected_names:
            continue
        try:
            stale.unlink()
            _warn("已删除过期凭据: %s（不在当前 accounts.yaml 清单中）" % stale.relative_to(root))
        except OSError as exc:
            _warn("删除过期凭据失败 %s: %s" % (stale, exc))

    if not accounts:
        _warn("devin_pool.accounts 为空，未生成任何 Devin 凭据")

    monitor = config.get("monitoring") or {}
    if not isinstance(monitor, dict):
        raise PoolctlError("accounts.yaml 的 monitoring 必须是映射(dict)")
    monitor.setdefault("enabled", True)

    # --- 2. cliproxy/config.yaml ------------------------------------------
    words = _sensitive_words(devin_pool)
    cliproxy_config = _build_cliproxy_config(env, mode, words, goat_keys, go_keys, monitor)
    cliproxy_path = root / "cliproxy" / "config.yaml"
    cliproxy_text = YAML_HEADER + yaml.safe_dump(
        cliproxy_config,
        allow_unicode=True,
        sort_keys=False,
        default_flow_style=False,
        width=120,
    )
    atomic_write_text(cliproxy_path, cliproxy_text)
    _ok("已生成 %s (config-version 8, mode=%s)" % (cliproxy_path.relative_to(root), mode))

    # --- 3. opencode2api/config.json --------------------------------------
    oc2api_config = _build_opencode2api_config(env, go_keys, proxies)
    oc2api_path = root / "opencode2api" / "config.json"
    atomic_write_json(oc2api_path, oc2api_config)
    _ok("已生成 %s (go_keys=%d, proxies=%d)" % (oc2api_path.relative_to(root), len(go_keys), len(proxies)))

    # --- 4. nginx 入口配置 -------------------------------------------------
    nginx_dir = root / "nginx" / "conf.d"
    nginx_dir.mkdir(parents=True, exist_ok=True)
    nginx_path = nginx_dir / "orca.conf"
    atomic_write_text(nginx_path, _build_nginx_conf(env))
    snippet_dir = root / "nginx" / "snippets"
    snippet_dir.mkdir(parents=True, exist_ok=True)
    atomic_write_text(snippet_dir / "orca-proxy.conf", NGINX_SNIPPET)
    _ok(
        "已生成 %s (公网 :%s + TLS 443 → CPA :%s，仅管理面限流)"
        % (
            nginx_path.relative_to(root),
            env.get("GATEWAY_PORT") or DEFAULT_GATEWAY_PORT,
            env.get("GATEWAY_INTERNAL_PORT") or DEFAULT_INTERNAL_PORT,
        )
    )

    if len(go_keys) > 5 and proxies == ["direct"]:
        _warn(
            "OpenCode Go key 数 %d > 5 且 proxies 仍为 [\"direct\"]："
            "建议在 accounts.yaml 的 opencode_go_pool.proxies 配置 2~3 个静态 SOCKS5/HTTP 代理以防封号"
            % len(go_keys)
        )
    if goat_keys:
        _info("command-code-goat 上游组已启用，key 数 %d" % len(goat_keys))
    else:
        _info("command_code_goat_pool 为空，已省略 command-code-goat 上游组")

    _emit("")
    _info("汇总: Devin 账号 %d（Pro %d / Max %d），模式 %s" % (len(accounts), pro_count, max_count, mode))
    if mode == "max-hybrid" and max_count == 0:
        _warn("max-hybrid 模式下没有 Max 号，所有流量仍会落在 Pro 号上")
    if words:
        _info("Devin 敏感词混淆已启用，词条数 %d" % len(words))
    else:
        _info("Devin 敏感词混淆未启用（sensitive_words.enabled=false）")

    _sync_opencode2api_container(root, oc2api_path, env)
    _check_plugin_reload(root, cliproxy_config)
    return 0


