def _emit(text=""):
    try:
        print(text, flush=True)
    except BrokenPipeError:
        # 下游管道被截断（如 `| head`）：静默退出，避免 Python 解释器再报 BrokenPipeError
        try:
            sys.stdout.close()
        except Exception:
            pass
        os._exit(0)


