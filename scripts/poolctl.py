def parse_env_file(path):
    """.env 手写解析器：KEY=VALUE、# 注释、可选 export 前缀与引号。"""
    values = {}
    text = Path(path).read_text(encoding="utf-8").lstrip("\ufeff")
    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export ") :].strip()
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        if not key:
            continue
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
            value = value[1:-1]
        else:
            for marker in (" #", "\t#"):
                index = value.find(marker)
                if index >= 0:
                    value = value[:index]
            value = value.strip()
        values[key] = value
    return values


def load_env(root):
    """读取 .env（缺失容错），并允许进程环境变量兜底。"""
    values = dict(os.environ)
    path = Path(root) / ".env"
    if path.exists():
        values.update(parse_env_file(path))
    else:
        _warn("未找到 %s，使用进程环境变量与默认值" % path)
    values.setdefault("GATEWAY_PORT", str(DEFAULT_GATEWAY_PORT))
    values.setdefault("OC2API_WEBUI_USER", "admin")
    return values


